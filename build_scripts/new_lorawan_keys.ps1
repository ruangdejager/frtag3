# new_lorawan_keys.ps1
#
# Creates fr_app/Worker/LoRaWan/lorawan_keys.h - the git-ignored file that holds
# the OTAA join credentials compiled into every frtag3 image - with a freshly
# generated random AppKey.
#
# Why the key is made here and not in the TTN console: the pilot fleet shares
# one AppKey (agreed 2026-09-29, see lorawan_keys_template.h), and it has to
# exist before the first tag does. Generated locally, it goes into the build
# straight away, and the production station (production/provision_tag.ps1)
# copies it into the TTN import file for every tag it passes, so no one ever
# types a key into the console. In TTN, registering by import (or by hand with
# "AppKey" pasted from this file) is all that is needed.
#
# The key is never printed. Open lorawan_keys.h to read it.
#
# Replacing an existing key is refused unless -Force is given, because every
# tag already built with the old key and every TTN registration made with it
# would stop joining. Do that only before any tag has been registered.
#
# The key comes from the OS cryptographic RNG
# (System.Security.Cryptography.RandomNumberGenerator), not Get-Random.
#
# Examples
#   .\build_scripts\new_lorawan_keys.ps1
#   .\build_scripts\new_lorawan_keys.ps1 -JoinEui 70B3D57ED0000000
#   .\build_scripts\new_lorawan_keys.ps1 -Force          (replace an unused key)

[CmdletBinding()]
param(
    # JoinEUI (AppEUI), 16 hex digits. All zeros is what the pilot uses; it
    # must equal the JoinEUI the tags are registered with in TTN.
    [ValidatePattern('^[0-9A-Fa-f]{16}$')]
    [string] $JoinEui = '0000000000000000',
    [switch] $Force
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

$dir      = Join-Path $PSScriptRoot '..\fr_app\Worker\LoRaWan'
$template = Join-Path $dir 'lorawan_keys_template.h'
$target   = Join-Path $dir 'lorawan_keys.h'

if (-not (Test-Path $template)) { throw "template not found: $template" }

if (Test-Path $target) {
    $existing = Get-Content -Path $target -Raw
    $unedited = $existing -match '(?m)^\s*#define\s+FRTAG_LORAWAN_APP_KEY\s+00(\s*,\s*00){15}\s*$'
    if (-not $unedited -and -not $Force) {
        Write-Host "lorawan_keys.h already holds a key - left unchanged." -ForegroundColor Yellow
        Write-Host "Replacing it strands every tag built and registered with it; re-run with -Force only if none are." -ForegroundColor Yellow
        exit 1
    }
}

function Format-CBytes([byte[]] $bytes) { ($bytes | ForEach-Object { '{0:X2}' -f $_ }) -join ',' }

$key = New-Object byte[] 16
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
try { $rng.GetBytes($key) } finally { $rng.Dispose() }

$joinBytes = [byte[]]@(0..7 | ForEach-Object { [Convert]::ToByte($JoinEui.Substring($_ * 2, 2), 16) })

# [^\r\n]* rather than .*: in .NET '.' also eats the '\r' of a CRLF line,
# which would leave the rewritten lines with bare LF endings.
$text = Get-Content -Path $template -Raw
$text = [regex]::Replace($text, '(?m)^([ \t]*#define[ \t]+FRTAG_LORAWAN_JOIN_EUI[ \t]+)[^\r\n]*',
                         { param($m) $m.Groups[1].Value + (Format-CBytes $joinBytes) })
$text = [regex]::Replace($text, '(?m)^([ \t]*#define[ \t]+FRTAG_LORAWAN_APP_KEY[ \t]+)[^\r\n]*',
                         { param($m) $m.Groups[1].Value + (Format-CBytes $key) })
$text = $text.Replace(' - REPLACE with the TTN key', ' - generated by build_scripts/new_lorawan_keys.ps1')

# ASCII, so the C preprocessor and the station's parser both read it plainly.
[System.IO.File]::WriteAllText((Resolve-Path $dir).Path + '\lorawan_keys.h', $text, [System.Text.Encoding]::ASCII)
[Array]::Clear($key, 0, $key.Length)

Write-Host "Wrote $target (JoinEUI $($JoinEui.ToUpper()), new random AppKey - open the file to read it)." -ForegroundColor Green
Write-Host "It is git-ignored: back it up somewhere safe. Losing it means re-registering every tag." -ForegroundColor Green
